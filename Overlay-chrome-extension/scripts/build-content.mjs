#!/usr/bin/env node
/**
 * Concatenate src/ fragments into content.js (single IIFE for MV3 MAIN world).
 * Users loading unpacked do NOT need to run this — content.js is committed.
 * Run after editing src/*: node Overlay-chrome-extension/scripts/build-content.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const orderPath = path.join(__dirname, 'module-order.json');
const order = JSON.parse(fs.readFileSync(orderPath, 'utf8'));

const parts = order.map((rel) => {
  const full = path.join(root, rel);
  if (!fs.existsSync(full)) {
    throw new Error('Missing module: ' + rel);
  }
  return fs.readFileSync(full, 'utf8').trimEnd();
});

const banner = `/* ============================================================
   Overlay MatchTimer — Chrome Extension Content Script
   Runs in MAIN world on InplayIP / Examino (OpenPlayer).
   Site-specific selectors & positioning live in SITE ADAPTERS;
   shared timer/HUD logic is shared below.

   SOURCE OF TRUTH: Overlay-chrome-extension/src/
   Generated by: node Overlay-chrome-extension/scripts/build-content.mjs
   Do not edit by hand — change src/* and rebuild.
   ============================================================ */
`;

const out = `${banner}
(function () {
    'use strict';

${parts.join('\n\n')}
})();
`;

const outPath = path.join(root, 'content.js');
fs.writeFileSync(outPath, out);
console.log('[OMT build] Wrote', path.relative(process.cwd(), outPath), '(' + out.split('\n').length + ' lines from ' + order.length + ' modules)');
